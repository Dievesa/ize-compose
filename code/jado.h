static inline bool keyboardLayoutIsRightToLeft(KeyboardLayoutId id) {
    switch (id) {
        case KB_ARABIC:
        case KB_HEBREW:
        case KB_KURDISH_ARABIC:
        case KB_PASHTO:
        case KB_PERSIAN:
        case KB_URDU:
            return true;
        default:
            return false;
    }
}

